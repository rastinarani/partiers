import assert from 'node:assert/strict';
import { randomBytes, scryptSync } from 'node:crypto';
import { chromium } from 'playwright';
import { expect } from '@playwright/test';
import { MongoClient } from 'mongodb';

const { PARTIERS_TEST_URL: base, MONGODB_URI: uri, MONGODB_DB: name } = process.env;
assert.match(name ?? '', /^partiers_test_[a-f0-9]+$/);
for (const url of [base, uri]) assert.ok(['localhost','127.0.0.1'].includes(new URL(url).hostname));
const client = new MongoClient(uri);
const db = client.db(name);
const tag = randomBytes(8).toString('hex');
const email = `customer-${tag}@example.invalid`;
const adminEmail = `admin-${tag}@example.invalid`;
const otherEmail = `other-${tag}@example.invalid`;
const password = randomBytes(24).toString('hex');
let browser;
const errors = [];
async function api(context, path, method, data) {
  return context.request.fetch(`${base}${path}`, {method, data});
}
async function login(page, path, address) {
  await page.goto(`${base}${path}`);
  await page.getByLabel('Email', {exact:true}).fill(address);
  await page.getByLabel('Password', {exact:true}).fill(password);
  const response = page.waitForResponse(r => r.url().endsWith(path.startsWith('/admin') ? '/api/admin/login' : '/api/auth/login') && r.request().method() === 'POST');
  await page.getByRole('button',{name:'Log in',exact:true}).click();
  const result = await response;
  assert.equal(result.status(), 200, 'Real login must succeed');
  const cookieName = path.startsWith('/admin') ? 'partiers_admin_session' : 'partiers_user_session';
  const issued = (await result.allHeaders())['set-cookie']?.match(new RegExp(`${cookieName}=([^;]+)`))?.[1];
  assert.ok(issued, 'Login must issue a cookie');
  await expect.poll(async () => (await page.context().cookies()).find(c => c.name === cookieName)?.value === issued).toBe(true);
}
try {
  assert.equal(await db.collection('admins').countDocuments(), 0);
  // Generated credentials exist only in the runner's random disposable database.
  const salt = randomBytes(16).toString('hex');
  await db.collection('admins').insertOne({name:'Temporary admin', email:adminEmail, passwordSalt:salt, passwordHash:scryptSync(password,salt,64).toString('hex'), createdAt:new Date().toISOString()});
  browser = await chromium.launch();
  const customer = await browser.newContext({viewport:{width:390,height:844},timezoneId:'Asia/Tokyo'});
  const admin = await browser.newContext();
  const other = await browser.newContext();
  const page = await customer.newPage();
  const manage = await admin.newPage();
  const outsider = await other.newPage();
  for (const p of [page,manage,outsider]) p.on('pageerror',e=>errors.push(e.message));
  await page.goto(`${base}/signup?next=${encodeURIComponent('/?booking=1')}`);
  await page.getByLabel('Name',{exact:true}).fill('E2E parent');
  await page.getByLabel('Email',{exact:true}).fill(email);
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Sign up',exact:true}).click();
  await page.waitForURL(`${base}/?booking=1`);
  await page.getByRole('button',{name:'Next month'}).click();
  await page.locator('[data-motion="entrance"].grid button:not([disabled])').filter({hasText:/^15$/}).click();
  await page.getByRole('button',{name:'Next',exact:true}).click();
  await expect(page.getByLabel('Start time')).toBeEnabled();
  await page.getByLabel('Start time').selectOption('14:00');
  await page.getByRole('button',{name:'Next',exact:true}).click();
  await page.getByLabel('What kind of event?').selectOption('birthday');
  await page.getByLabel('Address or general area').fill('Temporary E2E park');
  await page.getByRole('button',{name:'Next',exact:true}).click();
  await expect(page.getByLabel('Your name',{exact:true})).toHaveValue('E2E parent');
  await expect(page.getByLabel('Phone or email')).toHaveValue(email);
  await page.getByLabel("Child's name",{exact:true}).fill(`Child ${tag}`);
  await page.getByLabel("Child's age",{exact:true}).fill('7');
  await page.getByRole('button',{name:'Next',exact:true}).click();
  await page.getByRole('button',{name:'Send booking request'}).click();
  await expect(page.getByRole('heading',{name:'Request sent!'})).toBeVisible();
  const booking = await db.collection('bookings').findOne({contact:email});
  const user = await db.collection('users').findOne({email});
  assert.equal(booking.userId,user._id.toString());
  assert.equal(booking.status,'pending');
  await page.goto(`${base}/account`);
  await page.waitForLoadState("networkidle");
  await expect(page.locator('#main-content').getByText(`Ref ${booking.referenceCode}`,{exact:true})).toBeVisible();
  await page.getByLabel('Name',{exact:true}).fill('E2E updated');
  await page.getByLabel('Phone',{exact:false}).fill('6045550100');
  await page.getByRole('button',{name:'Save details'}).click();
  await expect(page.getByRole('status').filter({hasText:'Saved!'})).toBeVisible();
  // Another customer can neither see nor cancel this family's booking.
  await outsider.goto(`${base}/signup?next=https://example.invalid`);
  await outsider.getByLabel('Name',{exact:true}).fill('Other parent');
  await outsider.getByLabel('Email',{exact:true}).fill(otherEmail);
  await outsider.getByLabel('Password',{exact:true}).fill(password);
  await outsider.getByRole('button',{name:'Sign up',exact:true}).click();
  await outsider.waitForURL(`${base}/account`);
  assert.ok(!(await outsider.content()).includes(booking.referenceCode));
  assert.equal((await api(other,`/api/account/bookings/${booking._id}/cancel`,'POST')).status(),404);
  assert.equal((await api(customer,'/api/bookings','PATCH',{id:booking._id.toString(),status:'confirmed',force:true})).status(),401);
  await outsider.goto(`${base}/admin`);
  await outsider.waitForURL(`${base}/admin/login`);
  // Exercise the real login handler with the disposable admin.
  await login(manage,'/admin/login',adminEmail);
  await manage.waitForURL(`${base}/admin`);
  await manage.waitForLoadState("networkidle");
  await manage.goto(`${base}/admin/bookings/${booking._id}`);
  await manage.waitForLoadState("networkidle");
  await manage.getByLabel('Private admin notes').fill(`PRIVATE-${tag}`);
  await manage.getByRole('button',{name:'Save private notes'}).click();
  await expect.poll(async()=> (await db.collection('bookings').findOne({_id:booking._id})).adminNotes).toBe(`PRIVATE-${tag}`);
  await manage.waitForLoadState("networkidle");
  await manage.reload();
  await manage.waitForLoadState("networkidle");
  await expect(manage.getByLabel('Private admin notes')).toHaveValue(`PRIVATE-${tag}`);
  // A failed action rolls back and can be retried.
  await manage.route('**/api/bookings',route=>route.fulfill({status:503,json:{error:'Temporary E2E failure'}}));
  await manage.getByRole('button',{name:'Confirm',exact:true}).click();
  await expect(manage.getByRole('alert').filter({hasText:'Temporary E2E failure'}).first()).toBeVisible();
  assert.equal((await db.collection('bookings').findOne({_id:booking._id})).status,'pending');
  await manage.unroute('**/api/bookings');
  await manage.getByRole('button',{name:'Confirm',exact:true}).click();
  await expect.poll(async()=> (await db.collection('bookings').findOne({_id:booking._id})).status).toBe('confirmed');
  await manage.waitForLoadState("networkidle");
  await manage.reload();
  await manage.waitForLoadState("networkidle");
  await expect(manage.getByRole('button',{name:'Confirm',exact:true})).toBeDisabled();
  await page.reload();
  await expect(page.locator('#main-content').getByText('confirmed',{exact:true})).toBeVisible();
  assert.ok(!(await page.content()).includes(`PRIVATE-${tag}`));
  const availability = await (await customer.request.get(`${base}/api/availability?date=${booking.date}`)).json();
  assert.deepEqual(Object.keys(availability).sort(),['blocked','taken']);
  assert.deepEqual(availability.taken,[{start:'14:00',end:'16:00'}]);
  // Intended override is explicit and admin-only.
  const copy = {...booking}; delete copy._id; delete copy.referenceCode; delete copy.requestKey; delete copy.requestHash;
  const clash = await db.collection('bookings').insertOne({...copy,status:'pending'});
  assert.equal((await api(admin,'/api/bookings','PATCH',{id:clash.insertedId.toString(),status:'confirmed'})).status(),409);
  assert.equal((await api(admin,'/api/bookings','PATCH',{id:clash.insertedId.toString(),status:'confirmed',force:true})).status(),200);
  await db.collection('bookings').deleteOne({_id:clash.insertedId});
  await page.getByRole('button',{name:'Cancel booking',exact:true}).click();
  await page.getByRole('button',{name:'Yes, cancel',exact:true}).click();
  await expect(page.locator('#main-content').getByText('cancelled',{exact:true})).toBeVisible();
  assert.equal((await api(customer,`/api/account/bookings/${booking._id}/cancel`,'POST')).status(),409);
  console.log('PASS: account ownership, admin confirmation, private notes, recovery and cancellation.');
  // Customer logout and real login return to the account page.
  await page.getByRole('button',{name:'Log out',exact:true}).click();
  await page.waitForURL(`${base}/login`);
  await login(page,'/login?next=%2Faccount',email);
  await page.waitForURL(`${base}/account`);
  await expect(page.getByRole('heading',{name:/Hi, E2E updated!/})).toBeVisible();
  await page.goto(`${base}/reviews`);
  await page.getByLabel('Your name',{exact:true}).fill(`Reviewer ${tag}`);
  await page.getByLabel('Comment',{exact:true}).fill(`Review text ${tag}`);
  await page.getByRole('button',{name:'Submit review'}).click();
  await expect(page.getByRole('status').filter({hasText:'Thanks for the review!'})).toBeVisible();
  await page.reload();
  await expect(page.locator('#main-content').getByText(`Review text ${tag}`,{exact:true})).toHaveCount(0);
  await manage.goto(`${base}/admin`);
  const reviewCard = manage.locator('section').filter({has:manage.getByRole('heading',{name:'Reviews',exact:true})}).locator('div.rounded-2xl').filter({hasText:`Review text ${tag}`}).last();
  await reviewCard.getByRole('button',{name:'Approve',exact:true}).click();
  await expect.poll(async()=> (await db.collection('reviews').findOne({name:`Reviewer ${tag}`})).status).toBe('approved');
  await page.reload();
  await expect(page.locator('#main-content').getByText(`Review text ${tag}`,{exact:true})).toBeVisible();
  await manage.waitForLoadState("networkidle");
  await manage.reload();
  await manage.waitForLoadState("networkidle");
  await reviewCard.getByRole('button',{name:'Reject',exact:true}).click();
  await expect.poll(async()=> (await db.collection('reviews').findOne({name:`Reviewer ${tag}`})).status).toBe('rejected');
  await page.reload();
  await expect(page.locator('#main-content').getByText(`Review text ${tag}`,{exact:true})).toHaveCount(0);
  // Admin logout revokes a copied cookie, verified through a direct API call.
  const copiedCookies = await admin.cookies();
  await manage.getByRole('button',{name:'Log out',exact:true}).click();
  await manage.waitForURL(`${base}/admin/login`);
  const copied = await browser.newContext();
  await copied.addCookies(copiedCookies);
  assert.equal((await api(copied,'/api/reviews','PATCH',{})).status(),401);
  assert.deepEqual(errors,[]);
  console.log('PASS: real customer signup/login, safe return, signed-in booking/history/profile/cancellation, cross-customer isolation, customer/admin permissions, real admin login/confirmation/private notes/retry/overlap override/logout revocation, review submission/approval/rejection/public visibility.');
} finally {
  await browser?.close();
  await db.collection('bookings').deleteMany({contact:email});
  await db.collection('users').deleteMany({email:{$in:[email,otherEmail]}});
  await db.collection('admins').deleteMany({email:adminEmail});
  await db.collection('reviews').deleteMany({name:`Reviewer ${tag}`});
  await db.collection('rateLimits').deleteMany({});
  await client.close();
}
